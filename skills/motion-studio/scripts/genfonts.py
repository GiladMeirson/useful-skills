#!/usr/bin/env python3
"""Regenerates src/fonts.ts from every @fontsource package installed in the project.

Add a font family to a video project (offline-safe, no Google Fonts fetch at render time):
  npm i @fontsource/<family-slug>              # e.g. @fontsource/fraunces, @fontsource/secular-one
  python <skill>/scripts/genfonts.py .         # run in the project folder; rewrites src/fonts.ts
Then use the family name (as printed below) in public/brand.json "fonts.display" / "fonts.mono".

Only latin + hebrew subsets, normal style, weights 300-900 (italic 400 for serif families) are bundled.
Standard library only.
"""
from __future__ import annotations

import json
import pathlib
import re
import sys

WANT = {"300", "400", "500", "600", "700", "800", "900"}
SUBSETS = ("latin", "hebrew")


def main():
    proj = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else ".").resolve()
    out_path = pathlib.Path(sys.argv[2]) if len(sys.argv) > 2 else proj / "src" / "fonts.ts"
    nm = proj / "node_modules" / "@fontsource"
    if not nm.is_dir():
        sys.exit("no node_modules/@fontsource here: run npm install in the project folder first")
    imports, entries, hebrew, summary = [], {}, [], {}
    for pkg in sorted(p for p in nm.iterdir() if p.is_dir()):
        meta = pkg / "metadata.json"
        if not meta.exists():
            continue
        m = json.loads(meta.read_text(encoding="utf-8"))
        fam = m.get("family") or pkg.name
        serif = m.get("category") == "serif"
        rows, seen = [], set()
        for css in sorted(pkg.glob("*.css")):
            w = css.stem.replace("-italic", "")
            italic = css.stem.endswith("-italic")
            if w not in WANT or (italic and not (serif and w == "400")):
                continue
            for blk in re.findall(r"@font-face\s*{([^}]*)}", css.read_text(encoding="utf-8")):
                f = re.search(r"files/([\w-]+-(%s)-%s-(normal|italic)\.woff2)" % ("|".join(SUBSETS), w), blk)
                if not f or f.group(1) in seen:
                    continue
                seen.add(f.group(1))
                ur = re.search(r"unicode-range:\s*([^;]+);", blk)
                var = "f_" + re.sub(r"\W", "_", f.group(1).replace(".woff2", ""))
                imports.append(f"import {var} from '@fontsource/{pkg.name}/files/{f.group(1)}';")
                rows.append(f"\t\t{{url: {var}, weight: '{w}', style: '{f.group(3)}', unicodeRange: '{ur.group(1).strip() if ur else ''}'}},")
                if f.group(2) == "hebrew" and fam not in hebrew:
                    hebrew.append(fam)
        if rows:
            entries[fam] = rows
            summary[fam] = len(rows)
    out = [
        "// GENERATED by scripts/genfonts.py from the installed @fontsource packages. Do not edit by hand:",
        "// npm i @fontsource/<family> and re-run `python <skill>/scripts/genfonts.py .`",
        "import {loadFont} from '@remotion/fonts';",
        *imports,
        "",
        "type Face = {url: string; weight: string; style: string; unicodeRange: string};",
        "export const FONT_FILES: Record<string, Face[]> = {",
    ]
    for fam, rows in entries.items():
        out.append(f"\t'{fam}': [\n" + "\n".join(rows) + "\n\t],")
    out += [
        "};",
        "",
        f"export const HEBREW_FONTS: string[] = {json.dumps(hebrew)};",
        "",
        "const loaded = new Set<string>();",
        "/** Registers every face of a bundled family (once). Returns the CSS family name. Unknown names fall back to Heebo. */",
        "export const useBundledFont = (family: string): string => {",
        "\tconst fam = FONT_FILES[family] ? family : 'Heebo';",
        "\tif (!loaded.has(fam)) {",
        "\t\tloaded.add(fam);",
        "\t\tfor (const f of FONT_FILES[fam] ?? []) {",
        "\t\t\tloadFont({family: fam, url: f.url, weight: f.weight, style: f.style, unicodeRange: f.unicodeRange || undefined, format: 'woff2'}).catch(() => undefined);",
        "\t\t}",
        "\t}",
        "\treturn fam;",
        "};",
        "",
    ]
    out_path.write_text("\n".join(out), encoding="utf-8")
    print(json.dumps({"fonts_ts": str(out_path), "families": summary, "hebrew": hebrew}, ensure_ascii=False))


if __name__ == "__main__":
    main()
